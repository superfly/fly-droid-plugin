#!/usr/bin/env python3
"""Prepare an unpublished Factory marketplace contribution from this package."""

import argparse
import json
from pathlib import Path
import shutil
import subprocess

from sync_shared import ROOT
from validate import validate


def prepare(root, catalog, mode):
    validate(root)
    manifest_path = catalog / ".factory-plugin/marketplace.json"
    manifest = json.loads(manifest_path.read_text())
    if any(entry["name"] == "fly" for entry in manifest["plugins"]):
        raise ValueError("Catalog already contains fly; review its existing entry instead")
    entry = json.loads((root / ".factory-plugin/marketplace.json").read_text())["plugins"][0]
    if mode == "copy":
        destination = catalog / "plugins/fly"
        if destination.exists():
            raise ValueError("Catalog plugin directory already exists")
        shutil.copytree(root / "plugins/fly", destination,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    else:
        if subprocess.check_output(["git", "-C", str(root), "status", "--porcelain"]).strip():
            raise ValueError("Commit the package before generating a pinned remote entry")
        sha = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"]).decode().strip()
        entry["source"] = {
            "source": "git-subdir",
            "url": "https://github.com/superfly/fly-droid-plugin.git",
            "path": "plugins/fly",
            "sha": sha,
        }
    manifest["plugins"].append(entry)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    (catalog / "fly-submission-body.txt").write_text(
        "Add Fly.io for Factory Droid\n\n"
        "Adds the Fly.io plugin: shared Fly and brand skills, a hosted browser-OAuth MCP connection, "
        "and confirmation hooks for recognized risky operations. Supports Fly.io operations and persistent "
        "Sprite development workflows. The maintained distribution is https://github.com/superfly/fly-droid-plugin; "
        "shared instructions and guard behavior are pinned from https://github.com/superfly/skills.\n\n"
        "The plugin runs no local server and contains no credentials. Model access in Factory and "
        "a Fly.io account are required for live use; Python 3 enables the confirmation hook. "
        "Resource creation can incur Fly.io charges.\n\n"
        "Validation evidence and reviewer steps: see SUBMISSION.md and VALIDATION.md in the distribution repository. "
        "Public repository access and the upstream-main source pin must be verified before submitting.\n\n"
        "Generated by Codex.\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, required=True, help="Clean local Factory-AI/factory-plugins checkout")
    parser.add_argument("--mode", choices=["copy", "git-subdir"], default="copy")
    args = parser.parse_args()
    try:
        prepare(ROOT, args.catalog.resolve(), args.mode)
    except (ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Submission preparation failed: {error}\n")
    print(f"Prepared {args.mode} contribution in {args.catalog}; nothing was pushed or submitted")
